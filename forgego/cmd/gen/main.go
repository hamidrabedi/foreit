package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	var (
		inputFile   = flag.String("input", "", "Input file containing Fields() method")
		outputFile  = flag.String("output", "", "Output file (default: input_gen.go)")
		packageName = flag.String("package", "", "Package name (default: auto-detect)")
	)
	flag.Parse()

	if *inputFile == "" {
		fmt.Fprintf(os.Stderr, "Usage: gogo-gen -input <file.go>\n")
		os.Exit(1)
	}

	if err := generate(*inputFile, *outputFile, *packageName); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

func generate(inputFile, outputFile, packageName string) error {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, inputFile, nil, parser.ParseComments)
	if err != nil {
		return fmt.Errorf("failed to parse file: %w", err)
	}

	if packageName == "" {
		packageName = node.Name.Name
	}

	var modelName string
	var fieldsMethod *ast.FuncDecl

	ast.Inspect(node, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.TypeSpec:
			if st, ok := x.Type.(*ast.StructType); ok {
				modelName = x.Name.Name
				_ = st
			}
		case *ast.FuncDecl:
			if x.Name.Name == "Fields" && x.Recv != nil {
				fieldsMethod = x
			}
		}
		return true
	})

	if modelName == "" {
		if fieldsMethod != nil && fieldsMethod.Recv != nil && len(fieldsMethod.Recv.List) > 0 {
			if ident, ok := fieldsMethod.Recv.List[0].Type.(*ast.Ident); ok {
				modelName = ident.Name
			}
		}
		if modelName == "" {
			return fmt.Errorf("no struct found in file and could not infer from Fields() method")
		}
	}

	if fieldsMethod == nil {
		return fmt.Errorf("no Fields() method found for %s", modelName)
	}

	fields := extractFields(fieldsMethod)

	if outputFile == "" {
		base := strings.TrimSuffix(inputFile, filepath.Ext(inputFile))
		outputFile = base + "_gen.go"
	}

	code := generateCode(packageName, modelName, fields)
	return os.WriteFile(outputFile, []byte(code), 0644)
}

type Field struct {
	Name       string
	Type       string
	IsPointer  bool
	IsPrimary  bool
	IsRequired bool
}

func extractFields(fn *ast.FuncDecl) []Field {
	var fields []Field
	var currentField *Field

	ast.Inspect(fn.Body, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.CallExpr:
			if sel, ok := x.Fun.(*ast.SelectorExpr); ok {
				if ident, ok := sel.X.(*ast.Ident); ok && ident.Name == "models" {
					fieldName := extractStringArg(x)
					if fieldName != "" {
						fieldType := mapTypeToGoType(sel.Sel.Name)
						if currentField != nil {
							currentField.IsPointer = shouldBePointer(currentField)
							fields = append(fields, *currentField)
						}
						currentField = &Field{
							Name:       fieldName,
							Type:       fieldType,
							IsPointer:  false,
							IsPrimary:  false,
							IsRequired: false,
						}
					}
				} else if currentField != nil {
					if sel.Sel.Name == "PrimaryKey" {
						currentField.IsPrimary = true
					} else if sel.Sel.Name == "Required" {
						currentField.IsRequired = true
					} else if sel.Sel.Name == "AutoIncrement" {
						currentField.IsPrimary = true
					}
				}
			}
		}
		return true
	})

	if currentField != nil {
		currentField.IsPointer = shouldBePointer(currentField)
		fields = append(fields, *currentField)
	}

	return fields
}

func extractStringArg(call *ast.CallExpr) string {
	if len(call.Args) == 0 {
		return ""
	}
	if lit, ok := call.Args[0].(*ast.BasicLit); ok && lit.Kind == token.STRING {
		return strings.Trim(lit.Value, `"`)
	}
	return ""
}

func mapTypeToGoType(astType string) string {
	switch astType {
	case "Int64":
		return "int64"
	case "String":
		return "string"
	case "Bool":
		return "bool"
	case "Time":
		return "time.Time"
	case "Float64":
		return "float64"
	default:
		return "interface{}"
	}
}

func shouldBePointer(f *Field) bool {
	if f.IsPrimary {
		return false
	}
	if f.IsRequired {
		return false
	}
	if strings.HasSuffix(f.Name, "ID") && f.Type == "int64" && f.Name != "ID" {
		return true
	}
	if f.Type == "time.Time" && f.Name != "CreatedAt" && f.Name != "UpdatedAt" {
		return true
	}
	return false
}

func generateCode(packageName, modelName string, fields []Field) string {
	var buf bytes.Buffer

	buf.WriteString("//go:build !ignore_autogenerated\n// +build !ignore_autogenerated\n\n")
	buf.WriteString("// Code generated by gogo-gen. DO NOT EDIT.\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", packageName))

	hasTime := false
	for _, f := range fields {
		if strings.Contains(f.Type, "time.Time") {
			hasTime = true
			break
		}
	}

	if hasTime {
		buf.WriteString("import (\n")
		buf.WriteString("\t\"time\"\n\n")
		buf.WriteString("\t\"github.com/forgego/forge/pkg/models\"\n")
		buf.WriteString(")\n\n")
	} else {
		buf.WriteString("import \"github.com/forgego/forge/pkg/models\"\n\n")
	}

	buf.WriteString(fmt.Sprintf("type %s struct {\n", modelName))
	buf.WriteString("\tmodels.Schema\n")

	for _, f := range fields {
		typeStr := f.Type
		if f.IsPointer {
			typeStr = "*" + typeStr
		}
		buf.WriteString(fmt.Sprintf("\t%s %s\n", f.Name, typeStr))
	}

	buf.WriteString("}\n\n")


	buf.WriteString(fmt.Sprintf("func (%s) TableName() string {\n", modelName))
	buf.WriteString(fmt.Sprintf("\treturn %q\n", toSnakeCase(modelName)+"s"))
	buf.WriteString("}\n\n")

	buf.WriteString(fmt.Sprintf("func (%s) Relations() []models.RelationDescriptor {\n", modelName))
	buf.WriteString("\treturn []models.RelationDescriptor{}\n")
	buf.WriteString("}\n\n")

	// Generate Fields() method from extracted fields
	// Note: This is a simplified version - the full Fields() should be in the source file
	// We generate a basic version here for schema registration
	buf.WriteString(fmt.Sprintf("func (%s) Fields() []models.FieldDescriptor {\n", modelName))
	buf.WriteString("\treturn []models.FieldDescriptor{\n")
	for _, f := range fields {
		fieldType := strings.ToLower(strings.TrimPrefix(f.Type, "*"))
		if fieldType == "int64" {
			buf.WriteString(fmt.Sprintf("\t\tmodels.Int64(%q)", f.Name))
			if f.IsPrimary {
				buf.WriteString(".PrimaryKey().AutoIncrement()")
			}
		} else if fieldType == "string" {
			buf.WriteString(fmt.Sprintf("\t\tmodels.String(%q)", f.Name))
			if f.IsPrimary {
				buf.WriteString(".PrimaryKey()")
			}
			if f.IsRequired {
				buf.WriteString(".Required()")
			}
		} else if fieldType == "bool" {
			buf.WriteString(fmt.Sprintf("\t\tmodels.Bool(%q)", f.Name))
		} else if fieldType == "time.time" {
			buf.WriteString(fmt.Sprintf("\t\tmodels.Time(%q)", f.Name))
		} else {
			buf.WriteString(fmt.Sprintf("\t\tmodels.String(%q)", f.Name))
		}
		buf.WriteString(",\n")
	}
	buf.WriteString("\t}\n")
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.String()
	}

	return string(formatted)
}


func toSnakeCase(s string) string {
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}
		result.WriteRune(r)
	}
	return strings.ToLower(result.String())
}
